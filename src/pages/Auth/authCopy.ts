export const useAuthCopy = (): AuthCopy => {
  const { language } = useLanguage();
  return language === 'fr' ? fr : en;
};

export const fill = (template: string, values: Record<string, string | number>) =>
  template.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? ''));

